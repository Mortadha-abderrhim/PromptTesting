import os
API_KEY = os.environ.get("API_KEY")
import requests

def response(prompt):
    
    url = 'https://hctlsrvb.edu.sot.tum.de/llm//v1/chat/completions'
    headers = {
    'Authorization': f'Bearer {API_KEY}',
    'Content-Type': 'application/json'
    }
    data = {
    "model": "gpt-oss-120b",
    "messages":[{"role": "user", "content": prompt}],
    "stream": False
    }
    response = requests.post(url, headers=headers, json=data)
    return response.json()["choices"][0]["message"]["content"]

### main
if __name__ == "__main__":
    topic = "Should kids be given homework?"
    essay = ""
    language="English"

    proxy = Proxy(generate_proxy=response, generate_llm=response)
    history = []
    while True:
        prompt = input("Student: ")
        if prompt.lower() == "exit":
            break
        history = proxy.response(history, prompt, essay, topic, language)
        print("############################################################\n")
        print(history)
        print("############################################################\n")
        print("Teacher: ", history[-1]["content"])



